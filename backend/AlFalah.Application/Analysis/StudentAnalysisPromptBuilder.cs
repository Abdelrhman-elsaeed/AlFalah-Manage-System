using System.Globalization;
using AlFalah.Application.DTOs.StudentAnalyzer;

namespace AlFalah.Application.Analysis;

/// <summary>
/// Verbatim v3.0 prompt contract from the standalone student-analyzer prototype.
/// Keep wording, section order, and generation parameters stable.
/// </summary>
public static class StudentAnalysisPromptBuilder
{
    public const string Version = "student-analyzer-v3.0-verbatim";
    public const string SystemPrompt = "أنت مرشد طلابي متخصص وخبير في علم النفس التربوي. تقدم تقارير نفسية وتربوية شاملة باللغة العربية الفصحى.";

    public static string Build(
        string studentName,
        IReadOnlyList<StudentAnalyzerDataPointDto> grantData,
        IReadOnlyList<StudentAnalyzerDataPointDto> deductionData)
    {
        var grantSection = grantData.Count > 0
            ? string.Join('\n', grantData.Select(d => $"  - {d.Column}: {d.Value}"))
            : "  - لا توجد بيانات منح";

        var deductionSection = deductionData.Count > 0
            ? string.Join('\n', deductionData.Select(d => $"  - {d.Column}: {d.Value}"))
            : "  - لا توجد مخالفات مسجلة";

        var grantTotal = grantData.Sum(d => d.NumericValue ?? 0m);
        var deductionTotal = deductionData.Sum(d => d.NumericValue ?? 0m);

        return $"""
أنت مرشد طلابي متخصص وخبير في علم النفس التربوي والإرشاد النفسي. 
لديك خبرة واسعة في تحليل سلوك الطلاب وتشخيص المشكلات التربوية وتقديم الحلول المناسبة.

البيانات التالية مستخرجة من تقرير "بنود المنح والخصم" لطالب من نظام Code Plus التعليمي:

**اسم الطالب:** {studentName}
**إجمالي المنح:** {FormatNumber(grantTotal)} نقطة
**إجمالي الخصم:** {FormatNumber(deductionTotal)} نقطة

**بنود المنح (السلوكيات الإيجابية المسجلة):**
{grantSection}

**بنود الخصم (السلوكيات السلبية المسجلة):**
{deductionSection}

المطلوب منك تقديم تقرير نفسي وتربوي احترافي وشامل يتضمن الأقسام التالية بالترتيب. 
اكتب كل قسم بوضوح وعمق، مستخدماً مصطلحات علم النفس التربوي. 
استند إلى نظريات تربوية معروفة (مثل بلوم، ماسلو، بياجيه، فيجوتسكي) حيث يناسب.
اكتب باللغة العربية الفصحى الواضحة.

اتبع هذا الهيكل بالضبط، وابدأ كل قسم بعنوانه المحدد:

## ملخص تنفيذي
اكتب ملخصاً موجزاً (3-5 جمل) عن الصورة العامة لهذا الطالب بناءً على بياناته.

## التشخيص النفسي والسلوكي
قدّم تحليلاً نفسياً عميقاً للطالب بناءً على أنماط سلوكه المسجلة. ناقش:
- النمط السلوكي العام للطالب
- الحالة النفسية المحتملة
- مستوى الدافعية والانتماء للمدرسة
- العوامل النفسية الكامنة وراء السلوكيات السلبية (إن وجدت)
استند إلى نظريات علم النفس التربوي المعتمدة.

## المشكلات المحددة وأسبابها
حدد المشكلات الرئيسية لهذا الطالب وفق الأولوية (من الأشد إلى الأخف). لكل مشكلة اذكر:
- اسم المشكلة وتعريفها التربوي
- الأسباب المحتملة (نفسية، أسرية، أقران، أكاديمية)
- انعكاساتها على المسيرة التعليمية

## خطة التدخل والحلول العملية
قدّم خطة تدخل إرشادية مفصّلة وقابلة للتطبيق تشمل:
- خطوات التدخل المرحلية (قصيرة المدى: أسبوع - شهر، متوسطة: شهر - 3 أشهر)
- أساليب إرشادية محددة (فردي، جماعي، سلوكي، معرفي)
- تقنيات واستراتيجيات التعامل مع الطالب
- مؤشرات النجاح والتقييم

## أساليب التعلم المناسبة
بناءً على خصائص هذا الطالب، حدد:
- أسلوب التعلم الأنسب له (بصري، سمعي، حركي، قرائي/كتابي)
- البيئة التعليمية المثلى
- الأنشطة والأساليب التدريسية الأكثر فعالية معه
- كيفية استثمار نقاط قوته في التعلم

## توصيات للأسرة
وجّه رسالة ونصائح عملية للأسرة تشمل:
- الدور المطلوب من الأسرة
- سلوكيات ينبغي تعزيزها في البيت
- سلوكيات ينبغي تجنبها
- كيفية التواصل البناء مع الطالب
- متى يجب التدخل المتخصص (طبيب نفسي / مراكز)

## توصيات للمعلمين
وجّه توصيات عملية للمعلمين تشمل:
- أسلوب التعامل الأمثل مع هذا الطالب داخل الفصل
- استراتيجيات التعزيز والتحفيز
- كيفية ضبط سلوكه دون تعزيز سلبي
- كيفية إشراكه في الأنشطة الصفية

## الخلاصة والتوقعات
اختم التقرير بـ:
- تقييم إجمالي لمستوى الخطورة (منخفض / متوسط / مرتفع)
- التوقعات المستقبلية إن تم التدخل المبكر
- التوقعات إن لم يتم التدخل
- أهم رسالة للمرشد الطلابي

قدم الإجابة بشكل منظم ومفصّل. كل قسم يجب أن يكون مفيداً وقابلاً للتطبيق الفعلي.
""";
    }

    private static string FormatNumber(decimal value) => value.ToString("0.############################", CultureInfo.InvariantCulture);
}
